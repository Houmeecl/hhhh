//    pueblo Lickanantay, y su lengua ES el ckunsa (grafía fijada por el
//    Consejo Lingüístico Ckunsa en 2021; antes ckunza/kunza/cunza).
//    Ofrecer "kunza" y "atacameño" por separado sería el mismo error que
